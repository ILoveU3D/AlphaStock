_NOTE_STAMP = "2026-09-18 00:00"


def _b(bid, title, statement, source, status, tags=(), links=(),
       body="", created=""):
    """Build one seed-brick spec dict."""
    return {"id": bid, "title": title, "statement": statement,
            "source": source, "status": status, "tags": list(tags),
            "links": list(links), "body": body, "created_at": created}


def _body(argument, note, extra=None):
    """Standard brick body: 论证 (+optional 适用与反例) + Field Notes."""
    parts = ["## 论证", argument]
    if extra:
        parts += ["", "## 适用与反例", extra]
    parts += ["", "## Field Notes",
              f"- [{_NOTE_STAMP}] (ai) {note}"]
    return "\n".join(parts) + "\n"


