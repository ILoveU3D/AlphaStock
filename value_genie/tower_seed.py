def _book_bricks():
    """Render _BOOKS tuples into seed-brick specs (book template body)."""
    out = []
    for slug, name, author, tags, thesis, seeds in _BOOKS:
        lines = ["## 论证", thesis, "", "## 砖坯（可分形为独立砖）"]
        lines += [f"- {s}" for s in seeds]
        lines += [
            "",
            "## Field Notes",
            f"- [{_NOTE_STAMP}] (ai) 成砖：藏书吸收（{author}"
            f"《{name}》）；status=principle=借来未验证，对话中真正"
            "调用/验证后升 law 并分形。",
        ]
        out.append(_b(slug, name, thesis, f"book:{name}", "principle",
                      tags=tags, body="\n".join(lines) + "\n"))
    return out


SEED_BRICKS = _CORE + _MASTERS + _CONVERSATIONS + _book_bricks()


def seed_tower(tower_dir, dry_run: bool = False) -> dict:
    """Idempotently write missing seed bricks into the tower directory.

    Existing ids are skipped (no overwrite, no version bump). The
    single axiom is written here via save_brick directly — add_brick
    rejects axiom status by design (seed is the only establishment
    channel). Returns {"added", "skipped", "total"}.
    """
    d = Path(tower_dir)
    d.mkdir(parents=True, exist_ok=True)
    existing, _ = tw.load_bricks(d)
    known = {b.id for b in existing}
    seed_ids = [s["id"] for s in SEED_BRICKS]
    if len(set(seed_ids)) != len(seed_ids):
        dupes = sorted({x for x in seed_ids if seed_ids.count(x) > 1})
        raise tw.TowerFormatError(f"duplicate seed ids: {', '.join(dupes)}")
    universe = known | set(seed_ids)      # links may point inside the seed

    added = skipped = 0
    for spec in SEED_BRICKS:
        if spec["id"] in known:
            skipped += 1
            continue
        for link in spec["links"]:
            target = link.split(":", 1)[1]
            if target not in universe:
                raise tw.TowerFormatError(
                    f"seed brick {spec['id']!r}: link target {target!r} "
                    "not found in tower or seed set")
        if not dry_run:
            b = tw.Brick(id=spec["id"], title=spec["title"],
                         statement=spec["statement"],
                         source=spec["source"], status=spec["status"],
                         tags=list(spec["tags"]),
                         links=list(spec["links"]),
                         created_at=spec.get("created_at", ""),
                         body=spec["body"])
            b.version = 0                # first save lands at version 1
            tw.save_brick(d, b)
            known.add(b.id)
        added += 1
    total = (len(existing) + added) if dry_run else len(known)
    return {"added": added, "skipped": skipped, "total": total}
